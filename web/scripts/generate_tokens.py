"""Generates src/design/tokens.css and tokens.ts from the iOS FieldTokens.swift, so the web
prototype uses exactly the same Field DS values. Re-run when the Swift tokens change."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SWIFT = (ROOT / "Noon/DesignSystem/Field/FieldTokens.swift").read_text()
OUT = Path(__file__).resolve().parents[1] / "src/design"

def kebab(s):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", s)
    return s.lower()

def section(name):
    m = re.search(r"enum %s \{(.*?)\n\}" % name, SWIFT, re.S)
    return m.group(1)

colour_re = re.compile(r"static let (\w+) = Color\(fieldHex: 0x([0-9A-F]{6})(?:, alpha: ([0-9.]+))?\)")

def css_colour(hexv, alpha):
    if not alpha or float(alpha) >= 1:
        return "#" + hexv
    r, g, b = int(hexv[0:2], 16), int(hexv[2:4], 16), int(hexv[4:6], 16)
    return f"rgba({r}, {g}, {b}, {float(alpha):.3f})"

css = [":root {"]
ts = ["// AUTO-GENERATED by scripts/generate_tokens.py from FieldTokens.swift. Do not edit.", ""]

# Semantic colours
sem = section("FieldColour")
groups = {"TextNIcon": "text", "Surface": "surface", "Border": "border"}
ts.append("export const colour = {")
for swift_group, prefix in groups.items():
    body = re.search(r"enum %s \{(.*?)\}" % swift_group, sem, re.S).group(1)
    ts.append(f"  {prefix}: {{")
    for name, hexv, alpha in colour_re.findall(body):
        var = f"--{prefix}-{kebab(name)}"
        css.append(f"  {var}: {css_colour(hexv, alpha)};")
        ts.append(f"    {name}: 'var({var})',")
    ts.append("  },")
ts.append("} as const")
ts.append("")

# Palettes
pal = section("FieldPalette")
ts.append("export const palette = {")
for gname, body in re.findall(r"enum (\w+) \{(.*?)\}", pal, re.S):
    prefix = kebab(gname)
    ts.append(f"  {gname[0].lower() + gname[1:]}: {{")
    for name, hexv, alpha in colour_re.findall(body):
        key = name[1:] if re.fullmatch(r"c\d+", name) else name
        var = f"--{prefix}-{key}"
        css.append(f"  {var}: {css_colour(hexv, alpha)};")
        ts.append(f"    {key if not key.isdigit() else repr(key)}: 'var({var})',")
    ts.append("  },")
ts.append("} as const")
ts.append("")

# Space & radius
for enum, prefix in (("FieldSpace", "space"), ("FieldRadius", "radius")):
    body = section(enum)
    ts.append(f"export const {prefix} = {{")
    for name, val in re.findall(r"static let (\w+): CGFloat = (-?[0-9.]+)", body):
        ts.append(f"  {name}: {val},")
    ts.append("} as const")
    ts.append("")

css.append("}")

# Typography
weights = {"Light": 300, "Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700, "ExtraBold": 800, "Black": 900}
type_re = re.compile(r'static let (\w+) = FieldTextStyle\(fontName: "Noontree-(\w+)", size: ([0-9.]+), lineHeight: ([0-9.]+), letterSpacing: (-?[0-9.]+)(, strikethrough: true)?\)')
ts.append("import type { CSSProperties } from 'react'")
ts.append("")
ts.append("/** Field DS text styles: Noontree face, size, line height and tracking (px at the 375pt design). */")
ts.append("export const type = {")
for name, face, size, lh, ls, strike in type_re.findall(SWIFT):
    deco = ", textDecoration: 'line-through'" if strike else ""
    ts.append(f"  {name}: {{ fontFamily: 'var(--font-noon)', fontWeight: {weights[face]}, fontSize: {size}, lineHeight: '{lh}px', letterSpacing: {ls}{deco} }} as CSSProperties,")
ts.append("} as const")
ts.append("")
ts.append("export type TextStyleName = keyof typeof type")

# Fonts
faces = []
for face, w in weights.items():
    faces.append("@font-face { font-family: 'Noontree'; src: url('/fonts/Noontree-%s.otf') format('opentype'); font-weight: %d; font-style: normal; font-display: swap; }" % (face, w))

(OUT / "tokens.css").write_text("/* AUTO-GENERATED by scripts/generate_tokens.py. Do not edit. */\n" + "\n".join(faces) + "\n\n" + "\n".join(css) + "\n")
(OUT / "tokens.ts").write_text("\n".join(ts) + "\n")
print("ok")
