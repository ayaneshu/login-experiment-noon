#!/usr/bin/env python3
"""Generate FieldTokens.swift from the Field Design System's DTCG token JSON.

Usage:
    python3 Tools/generate_field_tokens.py <field-design-system>/packages/tokens/src/raw

The JSON in @field-ds/tokens is the source of truth. Never edit FieldTokens.swift by hand;
re-run this script when the design system changes.
"""
import json
import re
import sys
from pathlib import Path

RAW = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("field-design-system/packages/tokens/src/raw")
OUT = Path(__file__).resolve().parent.parent / "Noon/DesignSystem/Field/FieldTokens.swift"

base = json.loads((RAW / "base.json").read_text())
semantic = json.loads((RAW / "semantic.json").read_text())
text_styles = json.loads((RAW / "text-styles.json").read_text())
tree = {**base, **semantic}


def lookup(path):
    node = tree
    for part in path.split("."):
        node = node[part]
    return node


def resolve(value):
    if isinstance(value, str):
        match = re.fullmatch(r"\{(.+)\}", value)
        if match:
            target = lookup(match.group(1))
            return resolve(target["$value"] if isinstance(target, dict) and "$value" in target else target)
    return value


def number(value):
    value = resolve(value)
    if isinstance(value, (int, float)):
        return value
    return float(str(value).replace("px", "").replace("ms", ""))


def ident(name):
    parts = re.split(r"[-_\s]+", name)
    out = parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if out[0].isdigit():
        out = "s" + out
    return out.replace(".", "")


def hex_literal(value):
    value = resolve(value).lstrip("#")
    if len(value) == 6:
        return f"Color(fieldHex: 0x{value.upper()})"
    rgb, alpha = value[:6], int(value[6:8], 16) / 255
    return f"Color(fieldHex: 0x{rgb.upper()}, alpha: {alpha:.3f})"


def fmt(n):
    n = float(n)
    return str(int(n)) if n.is_integer() else f"{n:g}"


lines = [
    "// AUTO-GENERATED by Tools/generate_field_tokens.py from @field-ds/tokens (packages/tokens/src/raw).",
    "// Do not edit by hand. Re-run the script when the design system changes.",
    "",
    "import SwiftUI",
    "",
    "extension Color {",
    "    nonisolated init(fieldHex hex: UInt32, alpha: Double = 1) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255,",
    "                  blue: Double(hex & 0xFF) / 255, opacity: alpha)",
    "    }",
    "}",
    "",
    "/// Semantic colours: `colour.*` in @field-ds/tokens.",
    "enum FieldColour {",
]
for group, members in semantic["colour"].items():
    lines.append(f"    enum {ident(group)[0].upper() + ident(group)[1:]} {{")
    for key, token in members.items():
        lines.append(f"        static let {ident(key)} = {hex_literal(token['$value'])}")
    lines.append("    }")
lines.append("}")
lines.append("")

lines.append("/// Primitive palettes: `base.colour.*`. Prefer FieldColour; use these only where no semantic alias exists.")
lines.append("enum FieldPalette {")
for group, members in base["base"]["colour"].items():
    lines.append(f"    enum {ident(group)[0].upper() + ident(group)[1:]} {{")
    for key, token in members.items():
        lines.append(f"        static let {ident(key) if not key[0].isdigit() else 'c' + key} = {hex_literal(token['$value'])}")
    lines.append("    }")
lines.append("}")
lines.append("")

def scaled(n):
    """Dimensions follow the design scale (Figma is drawn at 375pt; wider phones scale up)."""
    return "0" if n == 0 else f"{fmt(n)} * FieldScale.factor"


lines.append("/// Spacing, scaled to the screen by `FieldScale`.")
lines.append("enum FieldSpace {")
for key, token in semantic["space"].items():
    name = "s" + key if not key.startswith("-") else "minus" + key[1:]
    lines.append(f"    static let {name}: CGFloat = {scaled(number(token['$value']))}")
lines.append("}")
lines.append("")

lines.append("/// Corner radii, scaled to the screen by `FieldScale`.")
lines.append("enum FieldRadius {")
for key, token in semantic["radius"].items():
    name = "r" + key if key[0].isdigit() else ident(key)
    value = number(token['$value'])
    lines.append(f"    static let {name}: CGFloat = {fmt(value) if value >= 999 else scaled(value)}")
lines.append("}")
lines.append("")

weights = {
    "Regular": "Noontree-Regular", "Medium": "Noontree-Medium", "SemiBold": "Noontree-SemiBold",
    "Bold": "Noontree-Bold", "ExtraBold": "Noontree-ExtraBold",
}
lines += [
    "/// A Field DS typography composite: Noontree face + size + line height + tracking.",
    "struct FieldTextStyle: Hashable, Sendable {",
    "    let fontName: String",
    "    let size: CGFloat",
    "    let lineHeight: CGFloat",
    "    let letterSpacing: CGFloat",
    "    var strikethrough = false",
    "}",
    "",
    "extension FieldTextStyle {",
]
for group, variants in text_styles.items():
    for variant, token in variants.items():
        value = token["$value"]
        weight = resolve(value["fontWeight"])
        name = ident(group.lower() + variant)
        strike = value.get("textDecoration") == "line-through"
        lines.append(
            f"    static let {name} = FieldTextStyle(fontName: \"{weights[weight]}\", size: {fmt(number(value['fontSize']))}, "
            f"lineHeight: {fmt(number(value['lineHeight']))}, letterSpacing: {fmt(number(value['letterSpacing']))}"
            + (", strikethrough: true)" if strike else ")")
        )
lines.append("}")
lines.append("")

motion = semantic["motion"]
lines.append("/// Motion tokens. Springs are converted from tension/friction to SwiftUI interpolating springs.")
lines.append("enum FieldMotion {")
lines.append("    enum Duration {")
for key, token in motion["duration"].items():
    lines.append(f"        static let {ident(key)}: Double = {number(token['$value']) / 1000:g}")
lines.append("    }")
lines.append("    enum Delay {")
for key, token in motion["delay"].items():
    lines.append(f"        static let {ident(key)}: Double = {number(token['$value']) / 1000:g}")
lines.append("    }")
lines.append("    enum Easing {")
for key, token in motion["easing"].items():
    a, b, c, d = token["$value"]
    lines.append(f"        static func {ident(key)}(_ duration: Double) -> Animation {{ .timingCurve({a:g}, {b:g}, {c:g}, {d:g}, duration: duration) }}")
lines.append("    }")
lines.append("    enum Spring {")
for key, token in motion["spring"].items():
    v = token["$value"]
    lines.append(f"        static let {ident(key)} = Animation.interpolatingSpring(mass: 1, stiffness: {v['tension']}, damping: {v['friction']})")
lines.append("    }")
lines.append("}")
lines.append("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(f"Wrote {OUT}")
